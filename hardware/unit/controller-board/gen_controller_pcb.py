# stitching vias (D-145, skill section 8): along the edge of each plane region, 1.0 mm inside it, pitch STITCH; a spot is
# skipped when it is near a pad or within 2 mm of a via already placed
STITCH, INSET = 5.0, 1.0
stitch = 0
for netname, poly in PLANES:
    for (xa, ya), (xb, yb) in zip(poly, poly[1:] + poly[:1]):
        L = ((xb - xa) ** 2 + (yb - ya) ** 2) ** 0.5; ux, uy = (xb - xa) / L, (yb - ya) / L
        for k in range(int(L // STITCH) + 1):
            for nx_, ny_ in ((-uy, ux), (uy, -ux)):                            # inward normal: the one that lands inside
                x, y = xa + ux * k * STITCH + nx_ * INSET, ya + uy * k * STITCH + ny_ * INSET
                if inside(x, y, poly) and edge_dist(x, y, poly) > INSET - 0.05: break
            else:
                continue
            ccx = X0 + RC if x < X0 + RC else (X1 - RC if x > X1 - RC else None)    # rounded board corners
            ccy = Y0 + RC if y < Y0 + RC else (Y1 - RC if y > Y1 - RC else None)
            if ccx is not None and ccy is not None and ((x - ccx) ** 2 + (y - ccy) ** 2) ** 0.5 > RC - INSET: continue
            if not clear_of_pads(x, y, None, CL_PLANE[netname]) or any((x - p) ** 2 + (y - q) ** 2 < 4.0 for p, q in VIAS): continue
            add_via(x, y, netname); VIAS.append((x, y)); stitch += 1
print("stitching vias", stitch)

