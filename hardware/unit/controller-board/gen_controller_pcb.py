def edge_dist(x, y, poly):
    m = 1e9
    for (xa, ya), (xb, yb) in zip(poly, poly[1:] + poly[:1]):
        dx, dy = xb - xa, yb - ya; t = max(0, min(1, ((x - xa) * dx + (y - ya) * dy) / (dx * dx + dy * dy)))
        m = min(m, ((x - xa - t * dx) ** 2 + (y - ya - t * dy) ** 2) ** 0.5)
    return m
