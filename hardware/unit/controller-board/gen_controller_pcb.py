def chamfer(pts, leg=0.45):
    """45-degree corners instead of 90-degree bends (Prins, 2026-10-23; hardware skill pcb-layout.md)."""
    q = [pts[0]]
    for (xa, ya), (xb, yb), (xc, yc) in zip(pts, pts[1:], pts[2:]):
        l1, l2 = ((xb - xa) ** 2 + (yb - ya) ** 2) ** 0.5, ((xc - xb) ** 2 + (yc - yb) ** 2) ** 0.5
        u1, u2 = ((xb - xa) / l1, (yb - ya) / l1), ((xc - xb) / l2, (yc - yb) / l2)
        if abs(u1[0] * u2[0] + u1[1] * u2[1]) > 0.01: q.append((xb, yb)); continue
        d = min(leg, 0.45 * l1, 0.45 * l2)
        q += [(round(xb - u1[0] * d, 4), round(yb - u1[1] * d, 4)), (round(xb + u2[0] * d, 4), round(yb + u2[1] * d, 4))]
    return q + [pts[-1]]
