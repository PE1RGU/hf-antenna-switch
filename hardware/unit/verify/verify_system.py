def startup(order):
    """order: list of firmware steps. Returns (loop current at the end, text trace)."""
    s = dict(fault=1, en_n=1, i=0)
    trace = []
    for step in order:
        if step == "LATCH_CLR": s["fault"] = 0
        elif step == "MCU_EN_N=0": s["en_n"] = 0
        elif step == "wait KILL=0":
            s["i"] = int(nor(s["en_n"], s["fault"]))
            if not s["i"]: trace.append("waits for KILL = 0: READY is 0, so the loop cannot close: **deadlock**"); return 0, trace
        s["i"] = int(nor(s["en_n"], s["fault"]))
        trace.append(f"{step}: READY {nor(s['en_n'], s['fault'])}, loop {s['i']}, KILL {1 - s['i']}")
    return s["i"], trace
