def latch_seq(events):
    q, pre_prev, rst_prev, trace = 1, 0, 0, []
    for ev in events:
        loop, power, rst = ev
        pre = int(loop and power)
        if not power: q = 1                                   # power-on reset sets the latch
        if not pre: q = 1                                     # PRE_N low sets Q
        elif rst and not rst_prev: q = 0                      # CLK edge with D = 0
        trace.append(q)
        rst_prev = rst
    return trace
