def is_state_allowed(tx, rx, k1, rx_only=frozenset({2})):
    """tx[r], rx[r]: column (1..4, 'E') or None per radio r; k1: set of columns with K1 on. True if no hazard H1 to H4."""
    for c in (1, 2, 3, 4):
        tx_r = [r for r in tx if tx[r] == c]
        any_r = {r for r in tx if tx[r] == c} | {r for r in rx if rx[r] == c}
        if len(tx_r) > 1: return False                             # H1
        if tx_r and any_r - {tx_r[0]}: return False                # H2
        if tx_r and c in rx_only: return False                     # H3
        if tx_r and c not in k1: return False                      # H4
    return True
