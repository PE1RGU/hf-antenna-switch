def run(td, tout, T, vdd_ok, wdi_fall, clr_rise, mcu_en_n, kill):
    """Return the list of (t_ms, RESET_N, FAULT, RLY_EN) at every change. Inputs are functions of t (ms)."""
    rst, flt, timer, low_until, hist = 0, 1, 0, None, []
    for t in range(T):
        if not vdd_ok(t):
            rst, low_until, timer = 0, None, 0
        elif rst == 0:
            if low_until is None: low_until = t + td
            if t >= low_until: rst, timer, low_until = 1, 0, None
        else:
            timer = 0 if wdi_fall(t) else timer + 1
            if timer >= tout: rst, low_until = 0, t + td
        if rst == 0: flt = 1                                   # PRE_N low sets Q
        elif clr_rise(t): flt = 0                             # CLK edge with D = 0, PRE_N high
        en = nor(kill(t), mcu_en_n(t), flt)
        if not hist or hist[-1][1:] != (rst, flt, en): hist.append((t, rst, flt, en))
    return hist

